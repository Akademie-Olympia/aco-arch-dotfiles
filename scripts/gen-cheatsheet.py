#!/usr/bin/env python3
"""Generate docs/cheatsheet.md from the component repositories.

    python3 scripts/gen-cheatsheet.py [--root DIR] [--check]

The Hyprland keys come from aco-hypr/hyprland.lua, tmux keys from
aco-tmux/keys, Neovim keys from aco-nvim/docs/_generated/keymaps.md. Curated
selections are validated against those sources: a key that disappeared from a
configuration makes this script (and CI, with --check) fail instead of leaving
a wrong key on the cheatsheet.
"""
import argparse
import csv
import importlib.util
from pathlib import Path
import re
import sys

HUB = Path(__file__).resolve().parent.parent
TARGET = HUB / "docs" / "cheatsheet.md"
DOCS = {"hypr": "aco-hypr", "tmux": "aco-tmux", "nvim": "aco-nvim", "vim": "aco-vim", "zsh": "aco-zsh"}

# (mode, key) pairs of the Neovim keymap table worth knowing first.
NVIM = [("n", "<leader><space>"), ("n", "<leader>ff"), ("n", "<leader>fg"), ("n", "<leader>fb"),
        ("n", "<leader>/"), ("n", "<leader>e"), ("n", "-"), ("n,i,x", "<C-s>"), ("n", "gd"),
        ("n", "<S-h>"), ("n", "<S-l>"), ("n", "<leader>bd"), ("n", "[d"), ("n", "]d"),
        ("n", "<leader>xx"), ("n", "<leader>db"), ("n", "<leader>dc"), ("n", "<leader>gd")]
# Hyprland rows (key text as rendered) outside the always-included groups.
HYPR_EXTRA = ["Super + C", "Super + F", "Super + V", "Super + Tab", "Alt + Tab", "Super + ←",
              "Super + Shift + ←", "Super + 1…0", "Super + Shift + 1…0", "Super + S"]
HYPR_GROUPS = ("Programme", "System", "Screenshots")
SHELL = [("`aco update`", "System aktualisieren (`pacman -Syu`) und Defaults zusammenführen"),
         ("`aco status`", "Zeigt, ob die Konfiguration aktiv ist"),
         ("`aco list`", "Installierte ACO-Pakete"),
         ("`aco install [modul]`", "Installierte Module aktivieren (ohne `sudo`)"),
         ("`aco deactivate [modul]`", "Vorherige Einstellungen wiederherstellen"),
         ("`aco path`", "Verzeichnis deiner bearbeitbaren Kopien"),
         ("`y`", "Yazi starten und danach im besuchten Verzeichnis bleiben"),
         ("`j <teil>`", "Per zoxide in ein häufig besuchtes Verzeichnis springen"),
         ("`tm`", "tmux-Sitzung `main` öffnen oder anhängen"),
         ("`nv` / `v`", "Neovim / Vim"),
         ("`wp`", "wallpaper-Befehl"),
         ("`dotfiles`", "In deine bearbeitbaren Konfigurationskopien wechseln")]


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def hypr_rows(root):
    module = load(root / DOCS["hypr"] / "scripts" / "gen-docs.py", "hypr_docs")
    rows = {}
    for number, key, action in module.bindings(module.SOURCE.read_text()):
        group, text = module.describe(action)
        rows.setdefault(key, (group, text or action))
    return rows


def tmux_rows(root):
    base = root / DOCS["tmux"] / "keys"
    descriptions = {}
    with open(base / "generated" / "keys.tsv", newline="") as handle:
        lines = [line for line in handle if not line.startswith("#")]
    for row in csv.DictReader(lines, delimiter="\t"):
        descriptions[(row["table"], row["key"].strip('"'))] = row["description"]
    quick = []
    for line in (base / "quick.tsv").read_text().splitlines():
        if line.startswith("#") or line.startswith("table\t") or not line.strip():
            continue
        table, key = line.split("\t")[:2]
        quick.append((table, key, descriptions.get((table, key))))
    return quick


def nvim_rows(root):
    rows = {}
    for line in (root / DOCS["nvim"] / "docs" / "_generated" / "keymaps.md").read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) >= 3 and cells[1].startswith("`"):
            rows.setdefault((cells[0].strip("`"), cells[1].strip("`")), cells[2])
    return rows


def render(root):
    errors = []
    out = ["<!-- GENERATED by scripts/gen-cheatsheet.py – do not edit by hand. -->", "",
           "# Cheatsheet", "",
           "Die wichtigsten Tasten und Befehle auf einen Blick. Alles hier wird aus den",
           "Konfigurationen erzeugt; die **vollständigen** Referenzen stehen in den Handbüchern",
           "der Komponenten. `Super` ist die Windows-Taste.", "",
           ":::{tip}", "In tmux öffnet {kbd}`Strg+b` dann {kbd}`H` den durchsuchbaren Key Explorer, in Neovim",
           "{kbd}`Space` (Leader) nach kurzer Pause which-key.", ":::", "",
           "::::{tab-set}", ""]
    rows = hypr_rows(root)
    out += [":::{tab-item} Desktop", "", "| Taste | Aktion |", "| --- | --- |"]
    for key, (group, text) in rows.items():
        if group in HYPR_GROUPS:
            out.append(f"| {{kbd}}`{key}` | {text} |")
    for key in HYPR_EXTRA:
        if key not in rows:
            errors.append(f"Hyprland binding missing: {key}")
        else:
            out.append(f"| {{kbd}}`{key}` | {rows[key][1]} |")
    out += ["", "Alle Belegungen: [Hyprland-Tastenkombinationen](https://aco-hypr.readthedocs.io/en/latest/keybindings/).",
            ":::", ""]
    out += [":::{tab-item} tmux", "", "`prefix` ist {kbd}`Strg+b`.", "", "| Taste | Aktion |", "| --- | --- |"]
    for table, key, text in tmux_rows(root):
        if text is None:
            errors.append(f"tmux key missing in registry: {table} {key}")
            continue
        shown = f"prefix {key}" if table == "prefix" else key
        out.append(f"| {{kbd}}`{shown}` | {text} |")
    out += ["", "Vollständig und durchsuchbar: [tmux-Tastenkombinationen](https://aco-tmux.readthedocs.io/en/latest/keybindings/quick/).",
            ":::", ""]
    nvim = nvim_rows(root)
    out += [":::{tab-item} Neovim", "", "`<leader>` ist {kbd}`Space`.", "", "| Taste | Aktion |", "| --- | --- |"]
    for mode, key in NVIM:
        if (mode, key) not in nvim:
            errors.append(f"Neovim keymap missing: {mode} {key}")
            continue
        out.append(f"| {{kbd}}`{key}` | {nvim[(mode, key)]} |")
    out += ["", "Alle Belegungen und Befehle: [Neovim-Handbuch](https://aco-nvim.readthedocs.io/en/latest/).", ":::", ""]
    out += [":::{tab-item} Vim", "",
            "Vim verwendet dieselben Leader-Belegungen wie Neovim (`<Space>`), siehe",
            "[Vim-Tastenkombinationen](https://aco-vim.readthedocs.io/en/latest/keybindings/).", ":::", ""]
    out += [":::{tab-item} Shell & Befehle", "", "| Befehl | Wirkung |", "| --- | --- |"]
    aliases = (root / DOCS["zsh"] / "aliases.zsh").read_text()
    for command, text in SHELL:
        names = re.findall(r"`(?:aco )?([a-z-]+)", command)
        if command.startswith("`y`") or command.startswith("`j "):
            pass
        elif command in ("`tm`", "`nv` / `v`", "`wp`", "`dotfiles`") and not all(
                re.search(rf"alias {n}=", aliases) for n in re.findall(r"`([a-z]+)`", command)):
            errors.append(f"zsh alias missing: {command}")
        out.append(f"| {command} | {text} |")
    out += ["", "Alle Befehle: [`aco`-Referenz](commands.md).", ":::", "", "::::", ""]
    return "\n".join(out), errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=HUB.parent)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    text, errors = render(args.root)
    for error in errors:
        print("error:", error, file=sys.stderr)
    if errors:
        return 1
    if args.check:
        if not TARGET.exists() or TARGET.read_text() != text:
            print("docs/cheatsheet.md is out of date; run scripts/gen-cheatsheet.py", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(HUB)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
